// Extracts the vector wordmark + tagline glyph paths from brand/jnb_logo.svg
// (a Canva export weighing ~670 kB, mostly C2PA metadata and embedded raster
// watermark art) and writes lean, recolourable assets:
//
//   src/assets/brand/jnb-wordmark.svg   wordmark only
//   src/assets/brand/jnb-lockup.svg     wordmark + tagline
//   src/lib/brand-paths.ts              the same paths for the PDF engine
//   public/favicon.svg, apple-touch-icon.png, logo.png
//
// Run with: npm run build:brand
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import sharp from 'sharp';

const src = readFileSync('brand/jnb_logo.svg', 'utf8');

// Canva wraps everything in translate(13,272). The tagline group adds (265,598).
const OUTER = [13, 272];
const TAGLINE_OFFSET = [265, 598];

// Glyph groups: <g fill="#9d6c0c" fill-opacity="N"><g transform="translate(x, y)"><g><path d="..."/>
const glyphRe =
  /<g fill="#9d6c0c" fill-opacity="([\d.]+)"><g transform="translate\(([-\d.]+), ([-\d.]+)\)"><g><path d="([^"]+)"/g;

const wordmark = [];
const tagline = [];
let taglineStarted = false;
const taglineMarker = src.indexOf('matrix(1, 0, 0, 1, 265, 598)');
if (taglineMarker < 0) throw new Error('tagline group not found');

for (const m of src.matchAll(glyphRe)) {
  const [, opacity, x, y, d] = m;
  if (Number(opacity) !== 1) continue; // drop the soft offset shadow copy
  taglineStarted = m.index > taglineMarker;
  (taglineStarted ? tagline : wordmark).push({ x: Number(x), y: Number(y), d });
}
if (!wordmark.length || !tagline.length) throw new Error('no glyphs extracted');

// Bake a translate into an absolute M/L/C/Z path (every number pair is a point).
function bake(d, dx, dy) {
  const tokens = d.match(/[MLCZ]|-?\d*\.?\d+/g);
  const out = [];
  let i = 0;
  let cmd = '';
  while (i < tokens.length) {
    const t = tokens[i];
    if (/[MLCZ]/.test(t)) {
      cmd = t;
      out.push(t);
      i++;
      continue;
    }
    const x = Number(tokens[i]) + dx;
    const y = Number(tokens[i + 1]) + dy;
    out.push(`${round(x)} ${round(y)}`);
    i += 2;
  }
  if (!cmd) throw new Error('bad path');
  return out.join(' ');
}
const round = (n) => Math.round(n * 100) / 100;

function build(glyphs, extra) {
  return glyphs.map((g) => bake(g.d, g.x + OUTER[0] + extra[0], g.y + OUTER[1] + extra[1])).join(' ');
}

const wordD = build(wordmark, [0, 0]);
const tagD = build(tagline, TAGLINE_OFFSET);

function bounds(d) {
  const nums = d.match(/-?\d*\.?\d+/g).map(Number);
  let x0 = Infinity,
    y0 = Infinity,
    x1 = -Infinity,
    y1 = -Infinity;
  for (let i = 0; i < nums.length; i += 2) {
    x0 = Math.min(x0, nums[i]);
    x1 = Math.max(x1, nums[i]);
    y0 = Math.min(y0, nums[i + 1]);
    y1 = Math.max(y1, nums[i + 1]);
  }
  return { x0, y0, x1, y1 };
}

const wb = bounds(wordD);
const tb = bounds(tagD);
const all = {
  x0: Math.min(wb.x0, tb.x0),
  y0: Math.min(wb.y0, tb.y0),
  x1: Math.max(wb.x1, tb.x1),
  y1: Math.max(wb.y1, tb.y1),
};

const pad = 6;
const box = (b) => ({
  x: round(b.x0 - pad),
  y: round(b.y0 - pad),
  w: round(b.x1 - b.x0 + pad * 2),
  h: round(b.y1 - b.y0 + pad * 2),
});
const wbox = box(wb);
const lbox = box(all);

const svg = (b, body, title) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${b.x} ${b.y} ${b.w} ${b.h}" role="img" aria-label="${title}" fill="currentColor">${body}</svg>\n`;

mkdirSync('src/assets/brand', { recursive: true });
writeFileSync('src/assets/brand/jnb-wordmark.svg', svg(wbox, `<path d="${wordD}"/>`, 'JNB Events'));
writeFileSync(
  'src/assets/brand/jnb-lockup.svg',
  svg(lbox, `<path d="${wordD}"/><path d="${tagD}"/>`, 'JNB Events — Decor, DJ, Mandaps'),
);

writeFileSync(
  'src/lib/brand-paths.ts',
  `// Generated by scripts/build-brand.mjs from brand/jnb_logo.svg. Do not edit by hand.
// Vector outlines of the JNB Events wordmark and tagline, in the logo's own coordinate space.

export const BRAND_WORDMARK = {
  d: ${JSON.stringify(wordD)},
  box: ${JSON.stringify(wbox)},
} as const;

export const BRAND_TAGLINE = {
  d: ${JSON.stringify(tagD)},
  box: ${JSON.stringify(box(tb))},
} as const;

export const BRAND_LOCKUP_BOX = ${JSON.stringify(lbox)} as const;
`,
);

// Favicon / app icons: the "J" (first glyph) in light gold on the site's night colour.
const jD = bake(wordmark[0].d, wordmark[0].x + OUTER[0], wordmark[0].y + OUTER[1]);
const jb = bounds(jD);
const jw = jb.x1 - jb.x0;
const jh = jb.y1 - jb.y0;
const SIZE = 64;
const scale = (SIZE * 0.56) / jh;
const tx = (SIZE - jw * scale) / 2 - jb.x0 * scale;
const ty = (SIZE - jh * scale) / 2 - jb.y0 * scale;
const jGroup = `<g transform="translate(${round(tx)} ${round(ty)}) scale(${round(scale * 1000) / 1000})" fill="#D6B36A"><path d="${jD}"/></g>`;
const icon = (rx) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${SIZE} ${SIZE}"><rect width="${SIZE}" height="${SIZE}" rx="${rx}" fill="#14110E"/>${jGroup}</svg>\n`;
writeFileSync('public/favicon.svg', icon(12));
await sharp(Buffer.from(icon(0)), { density: 600 }).resize(180, 180).png().toFile('public/apple-touch-icon.png');

// Square logo for structured data (Google wants a crawlable raster/SVG, min 112px, ideally square).
const lockupSvgGold = svg(lbox, `<path d="${wordD}"/><path d="${tagD}"/>`, 'JNB Events').replace('currentColor', '#9D6C0C');
const LW = 560;
const lockupPng = await sharp(Buffer.from(lockupSvgGold), { density: 400 }).resize({ width: LW }).png().toBuffer();
await sharp({ create: { width: 600, height: 600, channels: 3, background: '#FAF7F2' } })
  .composite([{ input: lockupPng, gravity: 'centre' }])
  .png({ compressionLevel: 9 })
  .toFile('public/logo.png');

console.log('wordmark box', wbox, 'lockup box', lbox);
